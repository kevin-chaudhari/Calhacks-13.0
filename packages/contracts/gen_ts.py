"""Generate packages/contracts/ts/index.ts from the Pydantic contracts (make contracts).

The Pydantic models are the source of truth. This emits camelCase TypeScript
interfaces from their JSON Schema (by_alias), so web and API field names match
exactly. No third-party generator needed.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from pydantic.json_schema import models_json_schema  # noqa: E402

import rally_contracts as c  # noqa: E402

MODELS = [c.DealSnapshot, c.IntentDraft, c.PrivatePrefs, c.PublicIntent, c.ApprovalRequest, c.Persona,
          c.ProposalMsg, c.ResponseMsg, c.QuoteRequestMsg, c.QuoteMsg, c.FinalAgreementMsg]


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x) for x in s["anyOf"]))
    t = s.get("type")
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "additionalProperties" in s and isinstance(s["additionalProperties"], dict):
            return f"Record<string, {ts_type(s['additionalProperties'])}>"
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(t, "unknown")


def main() -> None:
    _, schema = models_json_schema([(m, "serialization") for m in MODELS], by_alias=True)
    out = ["// GENERATED by packages/contracts/gen_ts.py from the Pydantic models. Do not edit by hand.",
           "// Run `make contracts` after changing anything in packages/contracts/rally_contracts.", ""]
    for name, d in sorted(schema["$defs"].items()):
        if "enum" in d and d.get("type") == "string":
            out.append(f"export type {name} = {ts_type(d)};\n")
            continue
        req = set(d.get("required", []))
        out.append(f"export interface {name} {{")
        for prop, ps in d.get("properties", {}).items():
            opt = "" if prop in req else "?"
            out.append(f"  {prop}{opt}: {ts_type(ps)};")
        out.append("}\n")
    target = HERE / "ts" / "index.ts"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target.relative_to(HERE.parents[1])} ({len(schema['$defs'])} types)")


if __name__ == "__main__":
    main()
